export function getSmmResourceContent(resource) {
  const module = SMM_MODULES.find((item) => item.resource === resource.slug);
  return [
    `CALEB CREATIVE — ${resource.title.toUpperCase()}`,
    '',
    resource.description,
    '',
    module?.checklist.map((item, index) => `${index + 1}. ${item}`).join('\n') || '',
    '',
    module?.exercise ? `EXERCICE\n${module.exercise}` : '',
    '',
    'À adapter à votre activité et à votre contexte. Ce modèle est un support de travail, pas une garantie de résultat.',
  ].join('\n');
}
